const DocsPage = () => {
    const [activeSection, setActiveSection] = useState('overview');
    const [searchQuery, setSearchQuery] = useState('');
    const [sidebarOpen, setSidebarOpen] = useState(false);
    const contentRef = useRef(null);

    useEffect(() => {
        if (contentRef.current) {
            contentRef.current.scrollTo(0, 0);
        }
    }, [activeSection]);

    const filteredSections = DOCS_SECTIONS.filter(s => 
        s.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
        s.content.toLowerCase().includes(searchQuery.toLowerCase())
    );

    const activeData = DOCS_SECTIONS.find(s => s.id === activeSection) || DOCS_SECTIONS[0];

    const parseMarkdown = (text) => {
        const lines = text.split('\n');
        const elements = [];
        let inTable = false;
        let tableRows = [];

        const pushTable = () => {
            if (tableRows.length > 0) {
                elements.push(
                    <div key={`table-${elements.length}`} className="docs-table-wrapper card">
                        <table>
                            <thead>
                                <tr>
                                    {tableRows[0].map((cell, i) => <th key={i}>{cell}</th>)}
                                </tr>
                            </thead>
                            <tbody>
                                {tableRows.slice(1).map((row, ri) => (
                                    <tr key={ri}>
                                        {row.map((cell, ci) => <td key={ci}>{cell}</td>)}
                                    </tr>
                                ))}
                            </tbody>
                        </table>
                    </div>
                );
                tableRows = [];
                inTable = false;
            }
        };

        lines.forEach((line, idx) => {
            if (line.startsWith('|')) {
                inTable = true;
                const cells = line.split('|').filter(c => c.trim() !== '' || line.startsWith('| |')).map(c => c.trim());
                if (!line.includes('---|')) {
                    tableRows.push(cells);
                }
            } else {
                pushTable();
                
                // Helper to render bold text correctly
                const renderLine = (text) => {
                    // Check for custom icon markers [ICON:Name]
                    const parts = text.split(/(\[ICON:.*?\]|\*\*.*?\*\*)/g);
                    return parts.map((part, i) => {
                        if (part.startsWith('[ICON:') && part.endsWith(']')) {
                            const iconName = part.replace('[ICON:', '').replace(']', '');
                            const IconComponent = {
                                'Layers': Layers,
                                'BookOpen': BookOpen,
                                'Book': Book,
                                'FileText': FileText,
                                'Cpu': Cpu
                            }[iconName];
                            return IconComponent ? <IconComponent key={i} size={18} style={{ verticalAlign: 'middle', margin: '0 4px', color: 'var(--c-brand)' }} /> : null;
                        }
                        if (part.startsWith('**') && part.endsWith('**')) {
                            return <strong key={i}>{part.slice(2, -2)}</strong>;
                        }
                        return part;
                    });
                };

                if (line.startsWith('## ')) elements.push(<h2 key={idx} className="docs-h2">{line.replace('## ', '')}</h2>);
                else if (line.startsWith('### ')) elements.push(<h3 key={idx} className="docs-h3">{line.replace('### ', '')}</h3>);
                else if (line.startsWith('- ') || line.startsWith('✅ ') || line.startsWith('❌ ')) elements.push(<li key={idx} className="docs-li">{renderLine(line.replace(/^- |^✅ |^❌ /, ''))}</li>);
                else if (line.startsWith('1. ') || line.match(/^\d+\. /)) elements.push(<li key={idx} className="docs-li-num">{renderLine(line.replace(/^\d+\. /, ''))}</li>);
                else if (line.startsWith('👉')) elements.push(<p key={idx} className="docs-link-line">{renderLine(line)}</p>);
                else if (line.startsWith('📞') || line.startsWith('📚')) elements.push(<p key={idx} className="docs-icon-line">{renderLine(line)}</p>);
                else if (line.trim() === '') elements.push(<div key={idx} className="docs-spacer" />);
                else if (!line.startsWith('```')) elements.push(<p key={idx} className="docs-p">{renderLine(line)}</p>);
            }
        });
        pushTable();
        return elements;
    };

    return (
        <div className="docs-page-root">
            <PublicNavbar />
            
            <div className="docs-layout">
                {/* Background Decorations */}
                <div className="docs-bg-decoration blob-1"></div>
                <div className="docs-bg-decoration blob-2"></div>

                <aside className={`docs-sidebar-premium ${sidebarOpen ? 'mobile-open' : ''}`}>
                    <div className="sidebar-inner">
                        <div className="sidebar-header-docs">
                            <BookOpen className="header-icon" />
                            <div>
                                <h3>Documentation</h3>
                                <span>Platform Guide</span>
                            </div>
                        </div>

                        <div className="docs-search-box">
                            <Search size={18} />
                            <input 
                                type="text" 
                                placeholder="Search everything..." 
                                value={searchQuery}
                                onChange={e => setSearchQuery(e.target.value)}
                            />
                        </div>

                        <nav className="docs-nav-list">
                            {DOCS_SECTIONS.map(section => (
                                <button 
                                    key={section.id}
                                    className={`docs-nav-item ${activeSection === section.id ? 'active' : ''}`}
                                    onClick={() => {
                                        setActiveSection(section.id);
                                        setSidebarOpen(false);
                                    }}
                                >
                                    <div className="item-icon">{section.icon}</div>
                                    <div className="item-text">
                                        <span className="item-title">{section.title}</span>
                                        <span className="item-subtitle">{section.subtitle}</span>
                                    </div>
                                    <ChevronRight size={16} className="chevron" />
                                </button>
                            ))}
                        </nav>

                        <div className="sidebar-footer-docs">
                            <div className="status-badge">
                                <span className="dot"></span> REB 2026 Ready
                            </div>
                            <span className="version">v2.1.0-Premium</span>
                        </div>
                    </div>
                </aside>

                <main className="docs-content-area" ref={contentRef}>
                    <div className="content-container">
                        <div className="docs-content-header animate-fade">
                            <div className="breadcrumb">
                                <Link to="/">Home</Link> / <span>Documentation</span> / <span>{activeData.title}</span>
                            </div>
                            <h1 className="content-main-title">{activeData.title}</h1>
                            <p className="content-subtitle">{activeData.subtitle}</p>
                        </div>

                        <div className="docs-rich-content animate-slide-up">
                            {parseMarkdown(activeData.content)}
                        </div>

                        <footer className="docs-content-footer">
                            <p>Was this helpful? Contact our support if you need more assistance.</p>
                            <div className="footer-actions">
                                <button className="btn btn-secondary btn-sm"><Mail size={16} /> Email Support</button>
                                <button className="btn btn-brand btn-sm"><Zap size={16} /> Get Started</button>
                            </div>
                        </footer>
                    </div>
                </main>

                {/* Mobile FAB */}
                <button 
                    className="docs-mobile-fab"
                    onClick={() => setSidebarOpen(!sidebarOpen)}
                >
                    {sidebarOpen ? <X /> : <Menu />}
                </button>
            </div>
        </div>
    );
};

export default DocsPage;
